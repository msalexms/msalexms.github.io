/**
 * Convierte una palabra, emote o garabato `{ doodle }` en una secuencia de trazos en px.
 * Devuelve `{ strokes, strokePx }` donde cada trazo es `[{ x, y }, ...]`.
 */
export function buildWordStrokes(item, w, h) {
  if (typeof item === 'object' && item?.doodle) {
    const polys = DOODLES[item.doodle] ?? [];
    return {
      strokes: polys.map((poly) => poly.map(([nx, ny]) => ({ x: nx * w, y: ny * h }))),
      strokePx: Math.max(8, Math.min(14, w * 0.032)),
    };
  }

  const chars = String(item).replaceAll('=)', '\u263A').toUpperCase().split('');
  const isSingleEmote = chars.length === 1 && chars[0] === '\u263A';
  const unitsPerChar = isSingleEmote ? 1.0 : 0.62;
  const gapUnits = 0.26;
  const totalUnits = chars.length * unitsPerChar + Math.max(0, chars.length - 1) * gapUnits;

  const maxWordW = isSingleEmote ? w * 0.58 : w * 0.76;
  const maxCharH = isSingleEmote ? h * 0.44 : h * 0.26;
  const charH = Math.min(maxCharH, maxWordW / Math.max(1, totalUnits));
  const charW = charH * unitsPerChar;
  const gap = charH * gapUnits;
  const wordW = chars.length * charW + Math.max(0, chars.length - 1) * gap;

  const startX = Math.max(12, Math.min(w - wordW - 12, (w - wordW) * (0.35 + Math.random() * 0.3)));
  const startY = Math.max(16, Math.min(h - charH - 16, (h - charH) * (0.28 + Math.random() * 0.44)));
  const tilt = (Math.random() - 0.5) * 0.1; // inclinación sutil en radianes
  const cx = startX + wordW / 2;
  const cy = startY + charH / 2;
  const cos = Math.cos(tilt);
  const sin = Math.sin(tilt);

  const strokes = [];
  chars.forEach((ch, idx) => {
    const ox = startX + idx * (charW + gap);
    const glyph = GLYPHS[ch] ?? [];
    for (const poly of glyph) {
      strokes.push(
        poly.map(([nx, ny]) => {
          const px = ox + nx * charW - cx;
          const py = startY + ny * charH - cy;
          return {
            x: cx + px * cos - py * sin,
            y: cy + px * sin + py * cos,
          };
        })
      );
    }
  });

  return { strokes, strokePx: charH * (isSingleEmote ? 0.13 : 0.16) };
}
